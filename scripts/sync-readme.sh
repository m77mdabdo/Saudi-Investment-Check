#!/usr/bin/env bash
# Regenerates the "Recent changes" block in README.md from git history.
#
# The block is delimited by HTML comments, so nothing else in the file is
# touched. Run it by hand, or install the post-commit hook:
#
#   bash scripts/hooks/install.sh
#
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
README="$ROOT/README.md"

[ -f "$README" ] || exit 0
grep -qF '<!-- changes:start -->' "$README" || exit 0

git -C "$ROOT" log -12 --date=short --format='| `%h` | %ad | %s |' > /tmp/.readme-changes.$$

python3 - "$README" "/tmp/.readme-changes.$$" <<'PY'
import io, sys
readme, rows_file = sys.argv[1], sys.argv[2]
rows = io.open(rows_file, encoding='utf-8').read().rstrip('\n')
start, end = '<!-- changes:start -->', '<!-- changes:end -->'
block = (f"{start}\n\n| Commit | Date | Change |\n| --- | --- | --- |\n{rows}\n\n"
         f"<sub>Generated by <code>scripts/sync-readme.sh</code>.</sub>\n{end}")
s = io.open(readme, encoding='utf-8').read()
a, b = s.index(start), s.index(end) + len(end)
new = s[:a] + block + s[b:]
if new != s:
    io.open(readme, 'w', encoding='utf-8').write(new)
    print('README changelog updated')
PY

rm -f "/tmp/.readme-changes.$$"
